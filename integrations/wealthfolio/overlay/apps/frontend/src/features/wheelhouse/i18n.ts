export const messages = { en, zh };

export function wheelhouseLocale(language: string | undefined): WheelhouseLocale {
  return language === "zh" || language?.startsWith("zh-Hans") ? "zh" : "en";
}

export function phrase(locale: WheelhouseLocale, key: MessageKey, vars?: Vars) {
  const template = messages[locale][key];
  if (!vars) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) =>
    vars[name] == null ? "" : String(vars[name]),
  );
}

export function labeled(text: TextFn, prefix: string, value: string) {
  const key = `${prefix}.${value}`;
  if (Object.prototype.hasOwnProperty.call(messages.en, key)) {
    return text(key as MessageKey);
  }
  return value.replaceAll("_", " ");
}

const knownIssues: Record<string, MessageKey> = {
  "History before the first input bar is unknown; counts cover this window only.":
    "issue.windowOnly",
};

export function issueText(text: TextFn, issue: string) {
  const key = knownIssues[issue];
  return key ? text(key) : issue;
}

export type TextFn = (key: MessageKey, vars?: Vars) => string;

export function useWheelhouseText() {
  const { i18n: bound } = useTranslation();
  const locale = wheelhouseLocale(bound.resolvedLanguage ?? bound.language);
  const text: TextFn = (key, vars) => phrase(locale, key, vars);
  return { locale, text };
}

export function wheelhouseNavLabel(
  key: "nav.brokerage" | "nav.cycles" | "nav.risk" | "nav.market" | "nav.marketHint",
) {
  return phrase(wheelhouseLocale(i18n.resolvedLanguage ?? i18n.language), key);
}
